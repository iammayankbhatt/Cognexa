"""Generate the endpoint reference in docs/API.md from the API itself (Phase 16).

Everything above the marker line in docs/API.md is hand-written (auth, errors, SSE events) and kept
as is; everything below it is regenerated from the FastAPI app: OpenAPI for paths, parameters and
request bodies, and the route dependencies for the Access column (public / signed in / role).

Usage: uv run --project apps/api python scripts/gen_api_docs.py [--check]
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from app.core.config import Settings
from app.core.route_walk import all_routes, depends_on, minimum_role
from app.main import create_app

DOC = Path(__file__).resolve().parents[1] / "docs" / "API.md"
MARKER = "<!-- Everything below is generated by scripts/gen_api_docs.py; do not edit by hand. -->"


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"]]
        return " | ".join(p for p in parts if p != "null") + (" | null" if "null" in parts else "")
    if "enum" in schema:
        return " | ".join(f"`{v}`" for v in schema["enum"])
    if "const" in schema:
        return f"`{schema['const']}`"
    t = schema.get("type", "any")
    if t == "array":
        return f"{_type(schema.get('items', {}))}[]"
    return str(t)


def _limits(schema: dict[str, Any]) -> str:
    out = []
    for key, label in (
        ("minLength", "min length"), ("maxLength", "max length"), ("minimum", "≥"),
        ("maximum", "≤"), ("minItems", "min items"), ("maxItems", "max items"),
        ("pattern", "pattern"),
    ):  # fmt: skip
        if key in schema:
            value = f"`{schema[key]}`" if key == "pattern" else schema[key]
            out.append(f"{label} {value}")
    for alt in schema.get("anyOf", []):
        out.extend(x for x in [_limits(alt)] if x)
    return ", ".join(out)


def _fields(name: str, schemas: dict[str, Any]) -> list[str]:
    schema = schemas.get(name, {})
    required = set(schema.get("required", []))
    rows = []
    for field, spec in schema.get("properties", {}).items():
        default = f" (default `{spec['default']}`)" if "default" in spec else ""
        limits = _limits(spec)
        rows.append(
            f"  - `{field}`{'' if field in required else '?'}: {_type(spec)}{default}"
            + (f"; {limits}" if limits else "")
        )
    return rows


def render() -> str:
    app = create_app(Settings(_env_file=None))
    spec = app.openapi()
    schemas = spec["components"]["schemas"]
    access: dict[tuple[str, str], str] = {}
    for method, path, route in all_routes(app):
        role = minimum_role(route.dependant)
        if role:
            access[(method, path)] = role
        elif depends_on(route.dependant, "get_current_user"):
            access[(method, path)] = "signed in"
        else:
            access[(method, path)] = "public"

    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = defaultdict(list)
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            groups[(op.get("tags") or ["other"])[0]].append((method.upper(), path, op))

    lines = [MARKER, "", "## Endpoint reference", ""]
    lines.append(
        f"{sum(len(v) for v in groups.values())} operations. **Access**: `public` needs no token, "
        "`signed in` needs a valid Supabase JWT, a role name means that role or higher "
        "(student < reviewer < admin). `?` marks an optional field."
    )
    for tag in sorted(groups):
        lines += ["", f"### {tag}", "", "| Method | Path | Access | Summary |", "|---|---|---|---|"]
        ops = sorted(groups[tag], key=lambda x: (x[1], x[0]))
        for method, path, op in ops:
            summary = op.get("summary", "")
            lines.append(f"| {method} | `{path}` | {access[(method, path)]} | {summary} |")
        details = []
        for method, path, op in ops:
            params = [p for p in op.get("parameters", []) if p.get("in") == "query"]
            body = (
                op.get("requestBody", {}).get("content", {}).get("application/json", {})
                or op.get("requestBody", {}).get("content", {}).get("multipart/form-data", {})
            )
            ref = body.get("schema", {}).get("$ref", "") if body else ""
            if not params and not ref:
                continue
            details.append(f"- **{method} `{path}`**")
            for p in params:
                req = "" if p.get("required") else "?"
                limits = _limits(p.get("schema", {}))
                details.append(
                    f"  - query `{p['name']}`{req}: {_type(p.get('schema', {}))}"
                    + (f"; {limits}" if limits else "")
                )
            if ref:
                name = ref.rsplit("/", 1)[-1]
                details.append(f"  - body `{name}`:")
                details += ["  " + row for row in _fields(name, schemas)]
        if details:
            lines += ["", *details]
    return "\n".join(lines) + "\n"


def main() -> int:
    current = DOC.read_text(encoding="utf-8").replace("\r\n", "\n")
    if MARKER not in current:
        print(f"{DOC} has no generator marker line")
        return 1
    text = current.split(MARKER, 1)[0] + render()
    if "--check" in sys.argv:
        if text != current:
            print(f"{DOC} is stale: run scripts/gen_api_docs.py")
            return 1
        print("docs/API.md is up to date.")
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
